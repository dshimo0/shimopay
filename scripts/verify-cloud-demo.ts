import {chromium,expect as baseExpect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const origin=new URL(process.argv[2]??'');
const expect=baseExpect.configure({timeout:60_000});
if(origin.protocol!=='https:'||!origin.hostname.endsWith('.vercel.run'))throw new Error('Expected a temporary Vercel Sandbox HTTPS URL');
const config=await fetch(new URL('/deployment.json',origin)).then(r=>r.json()) as {chainId:number;rpcUrl:string};
if(config.chainId!==31337||config.rpcUrl!=='/api/demo-rpc')throw new Error('Expected isolated local demo with same-origin RPC');
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE??'/usr/bin/chromium',args:['--no-sandbox'],proxy:process.env.HTTPS_PROXY?{server:process.env.HTTPS_PROXY}:undefined});
try{
 const context=await browser.newContext();const page=await context.newPage();
 await page.goto(new URL('/demo',origin).href);
 await expect(page.getByRole('button',{name:'Fund wallet',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Fund wallet',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('received 100 demo USDC');
 await page.getByLabel('Offline wallet password').fill('cloud-demo-test-password');
 await page.getByRole('button',{name:'Enable offline payments',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Offline allowance ready');
 await page.getByRole('button',{name:'Simulate offline',exact:true}).click();
 const requests:string[]=[];page.on('request',r=>{if(r.url().includes('/api/'))requests.push(r.url());});
 await page.getByRole('button',{name:'Charge',exact:true}).click();
 await page.getByRole('button',{name:'Pay offline',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Authorized locally');
 await page.getByRole('button',{name:'Validate & accept offline',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('PAYMENT ACCEPTED');expect(requests).toEqual([]);
 await page.getByRole('button',{name:'Restore connectivity',exact:true}).click();
 await page.getByRole('button',{name:/^Settle now/}).click();
 await expect(page.getByRole('status')).toContainText('PAYMENT SETTLED');
 const text=await page.getByTestId('transaction-hash').textContent();
 const hash=text?.match(/0x[0-9a-fA-F]{64}/)?.[0];if(!hash)throw new Error('Missing transaction hash');
 const receipt=await fetch(new URL('/api/demo-rpc',origin),{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:1,method:'eth_getTransactionReceipt',params:[hash]})}).then(r=>r.json()) as {result:{status:string;transactionHash:string}};
 expect(receipt.result.status).toBe('0x1');
 await page.getByText('Developer details & security checks').click();
 await page.getByRole('button',{name:'Test replay',exact:true}).click();await expect(page.getByRole('status')).toContainText('REPLAY REJECTED');
 await page.getByRole('button',{name:'Test tamper',exact:true}).click();await expect(page.getByRole('status')).toContainText('INVALID SIGNATURE');
 await page.getByRole('button',{name:'Disable offline payments',exact:true}).click();await expect(page.getByRole('status')).toContainText('Unspent funds released');
 await mkdir('docs/evidence',{recursive:true});
 await page.screenshot({path:'docs/evidence/cloud-demo.png',fullPage:true});
 const evidence={executedAt:new Date().toISOString(),url:new URL('/demo',origin).href,chainId:31337,txHash:hash,receiptStatus:receipt.result.status,offlineApiRequests:0,settlementMicroUsdc:'4545455',replay:'rejected',tamper:'invalid signature'};
 await writeFile('docs/evidence/cloud-demo.json',JSON.stringify(evidence,null,2));
 console.log(JSON.stringify(evidence,null,2));
}finally{await browser.close();}
